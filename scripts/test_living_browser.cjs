/** Optional Rheo Living Map browser QA. Requires Playwright and Chromium installed externally. */
const assert=require("node:assert/strict");
const {chromium}=require(process.env.RHEO_PLAYWRIGHT||"playwright");
const base=process.env.RHEO_TEST_URL||"http://127.0.0.1:8080/app/";
(async()=>{
  const launch={headless:true,args:["--no-sandbox"]};
  if(process.env.RHEO_CHROMIUM)launch.executablePath=process.env.RHEO_CHROMIUM;
  const browser=await chromium.launch(launch);
  const errors=[];
  try{
    const desktop=await browser.newPage({viewport:{width:1440,height:920}});
    desktop.on("pageerror",e=>errors.push(e.message));
    await desktop.goto(base);
    await desktop.locator("#portal-name").filter({hasText:"The Growing Place"}).waitFor();
    assert.equal(await desktop.locator("#portal-layer [data-portal]").count(),12);
    assert.match(await desktop.locator(".sandbox-pill").first().textContent(),/FICTIONAL/);
    await desktop.locator("#activate").click();
    await desktop.locator('[data-portal="kitchen"]').click();await desktop.locator("#activate").click();
    assert.match(await desktop.locator("#emergence-list").textContent(),/living soil/);
    await desktop.locator('[data-layer="roads"]').click();
    assert.equal(await desktop.locator("#route-layer").evaluate(el=>el.style.display),"none");
    await desktop.locator('[data-layer="both"]').click();
    if(process.env.RHEO_SCREENSHOTS)await desktop.screenshot({path:"docs/rheo-v04-desktop.png",fullPage:true});
    await desktop.locator('[data-view="matrix"]').click();
    await desktop.locator('[data-session="s1"]').click();await desktop.locator('[data-session="s2"]').click();
    assert.match(await desktop.locator("#path-warnings").textContent(),/Overlap/);
    assert.equal(await desktop.locator("#my-count").textContent(),"2");
    await desktop.locator("#make-session").click();
    await desktop.locator('#session-form [name="title"]').fill("Listening together");
    await desktop.locator('#session-form [name="time"]').fill("17:00");
    await desktop.locator("#session-form button[type=submit]").click();
    assert.match(await desktop.locator("#matrix-body").textContent(),/Listening together/);
    await desktop.locator('[data-view="studio"]').click();
    await desktop.locator("#outer-done").uncheck();
    assert.equal(await desktop.locator('#portal-form button[type=submit]').isDisabled(),true);
    await desktop.locator("#outer-done").check();
    await desktop.locator('#portal-form [name=name]').fill("An invented portal");
    await desktop.locator('#portal-form [name=invitation]').fill("Meet for a little while.");
    await desktop.locator('#portal-form button[type=submit]').click();
    assert.equal(await desktop.locator("#portal-layer [data-portal]").count(),13);
    await desktop.locator('[data-view="network"]').click();
    await desktop.locator("#meet").click();
    assert.match(await desktop.locator("#mesh-log").textContent(),/completed/);
    assert.equal(await desktop.locator(".device").nth(2).locator("li").count(),1);
    await desktop.locator("#peer-a").selectOption("B");await desktop.locator("#peer-b").selectOption("C");await desktop.locator("#meet").click();
    assert.equal(await desktop.locator(".device").nth(2).locator("li").count(),3);
    await desktop.locator('[data-view="pot"]').click();
    assert.match(await desktop.locator("#pot-metrics").textContent(),/£10,000/);
    await desktop.locator('#tithe-controls [name=year]').selectOption("5");
    await desktop.locator('#tithe-controls [name=localMonthly]').fill("0");
    assert.match(await desktop.locator("#pot-message").textContent(),/held at 100%/);
    await desktop.locator('#tithe-controls [name=localMonthly]').fill("4800");
    assert.match(await desktop.locator("#pot-message").textContent(),/meets the replacement/);
    const mobile=await browser.newPage({viewport:{width:390,height:844},isMobile:true});
    mobile.on("pageerror",e=>errors.push(e.message));
    await mobile.goto(base);await mobile.locator("#portal-name").filter({hasText:"The Growing Place"}).waitFor();
    assert.equal(await mobile.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true,"no mobile horizontal overflow");
    await mobile.locator('[data-view="matrix"]').click();
    assert.ok(await mobile.locator("#time-matrix").count());
    if(process.env.RHEO_SCREENSHOTS)await mobile.screenshot({path:"docs/rheo-v04-mobile.png",fullPage:true});
    assert.deepEqual(errors,[]);
    console.log("PASS v0.4 Living Map desktop/mobile, emergent portals, itinerary, curator controls, in-memory encounters and conditional Tithe Pot.");
  }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1});
